/**
 * External resource sources.
 *
 * This is the catalogue of the third-party libraries, generators and galleries
 * Cupric draws on — for two different jobs:
 *
 *   • `ui`    — patterns we mirror in the app's own interface (Lab components,
 *               glass chrome, Library cards, Studio panels).
 *   • `video` — material the local HTML → MP4 pipeline can render: backgrounds,
 *               shaders, illustrations, kinetic type, templates.
 *
 * Nothing here is bundled code. Each entry records *where* the material lives,
 * what licence story it has, and a `promptCue` the Arena/Gemini prompt builder
 * and the local generator can paste verbatim. That keeps the app honest: the
 * catalogue can list 40 sites while the repo stays small and MIT-clean.
 *
 * `resources/packs/sources.json` is generated from this file by
 * `npm run packs:build`, so the Library shows exactly what the code knows.
 */

export type SourceUse = 'ui' | 'video' | 'both'

export type SourceKind =
  | 'components'
  | 'shaders'
  | 'backgrounds'
  | 'illustrations'
  | 'icons'
  | 'motion'
  | 'templates'
  | 'generators'
  | 'inspiration'
  | 'prompts'

export type SourceEntry = {
  id: string
  name: string
  url: string
  kind: SourceKind
  use: SourceUse
  /** One line: what it actually gives us. */
  description: string
  /** Pasted into generation prompts and into the Arena brief. */
  promptCue: string
  /** How the material reaches Cupric: copy-paste, CLI registry, or reference only. */
  intake: 'copy' | 'registry' | 'reference' | 'export'
  /** Free / open-source unless noted. */
  license: string
  tags: string[]
}

