/** Sources usable by the local HTML → MP4 generator. */
export const VIDEO_SOURCES = SOURCES.filter((s) => s.use === 'video' || s.use === 'both')

/** Sources that inform the app's own interface. */
export const UI_SOURCES = SOURCES.filter((s) => s.use === 'ui' || s.use === 'both')

export function sourcesByKind(kind: SourceKind): SourceEntry[] {
  return SOURCES.filter((s) => s.kind === kind)
}

export function getSource(id: string): SourceEntry | undefined {
  return SOURCES.find((s) => s.id === id)
}
